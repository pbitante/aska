import { existsSync, mkdirSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { err, warn, type Diagnostic } from '../diagnostics';
import { isSymlink, writeAtomic } from '../fs';
import type { EffectivePersona } from '../model/effective';
import { generatedFileName, inputHash, outputStyleFile, readMarker, subagentFile } from './targets';

export type TargetScope = 'project' | 'user';

export interface RenderTargets {
  projectClaudeDir: string;
  userClaudeDir: string;
}

export interface RenderPlan {
  scope: TargetScope;
  files: { path: string; content: string }[];
}

export function chooseScope(p: EffectivePersona, requested?: TargetScope): { scope?: TargetScope; diagnostic?: Diagnostic } {
  const needed: TargetScope = p.inputScopes.includes('project') ? 'project' : 'user';
  if (requested === 'user' && needed === 'project') {
    return {
      diagnostic: err('E_RENDER_SCOPE', `${p.canonical} uses project-scope files, so it can only be rendered into the project scope`, undefined, 'Use --scope project'),
    };
  }
  return { scope: requested ?? needed };
}

export function planRender(p: EffectivePersona, targets: RenderTargets, requested?: TargetScope): { plan?: RenderPlan; diagnostics: Diagnostic[] } {
  const chosen = chooseScope(p, requested);
  if (!chosen.scope) return { diagnostics: [chosen.diagnostic!] };
  const root = chosen.scope === 'project' ? targets.projectClaudeDir : targets.userClaudeDir;
  const hash = inputHash(p);
  const file = generatedFileName(p);
  return {
    plan: {
      scope: chosen.scope,
      files: [
        { path: join(root, 'output-styles', file), content: outputStyleFile(p, hash) },
        { path: join(root, 'agents', file), content: subagentFile(p, hash) },
      ],
    },
    diagnostics: [],
  };
}

function isRegularFile(path: string): boolean {
  try {
    return statSync(path).isFile();
  } catch {
    return false;
  }
}

function isUnmarked(path: string): boolean {
  if (!existsSync(path)) return false;
  try {
    return !readMarker(readFileSync(path, 'utf8'));
  } catch {
    return true;
  }
}

export function writePlan(plan: RenderPlan): Diagnostic[] {
  // Never write through a symlink: a cloned repo could point a project path at the user's own
  // generated files (or anywhere else), and replacing the link instead would silently fork a
  // file the user linked on purpose. Refuse, and let the user decide.
  const linked = plan.files
    .filter((f) => isSymlink(f.path))
    .map((f) => err('E_RENDER_SYMLINK', `${f.path} is a symlink; refusing to write through it`, { file: f.path, line: 1 }, 'Remove the link (or replace it with a regular file), then render again'));
  if (linked.length > 0) return linked;
  const blocked = plan.files
    .filter((f) => isUnmarked(f.path))
    .map((f) => err('E_RENDER_UNMARKED', `${f.path} exists and was not generated by aska; refusing to overwrite it`, { file: f.path, line: 1 }, 'Move or rename that file, then render again'));
  if (blocked.length > 0) return blocked;
  const written: string[] = [];
  for (const f of plan.files) {
    try {
      mkdirSync(dirname(f.path), { recursive: true });
      writeAtomic(f.path, f.content);
    } catch (e) {
      const already = written.length > 0 ? ` (${written.join(', ')} ${written.length === 1 ? 'was' : 'were'} written)` : '';
      return [err('E_WRITE', `could not write ${f.path}: ${(e as Error).message}${already}`, { file: f.path, line: 1 }, 'Check permissions on the target directory, then render again')];
    }
    written.push(f.path);
  }
  return [];
}

export function findStaleRenders(
  targets: RenderTargets,
  resolve: (canonical: string) => EffectivePersona | undefined,
  runHint: (canonical: string) => string = (canonical) => `Run: persona render ${canonical}`,
  onlyFileName?: string,
): Diagnostic[] {
  const ds: Diagnostic[] = [];
  for (const dir of new Set([targets.projectClaudeDir, targets.userClaudeDir])) {
    for (const sub of ['output-styles', 'agents']) {
      let files: string[];
      try {
        files = readdirSync(join(dir, sub))
          .filter((f) => f.endsWith('.persona.md'))
          .filter((f) => onlyFileName === undefined || f === onlyFileName)
          .filter((f) => isRegularFile(join(dir, sub, f)))
          .sort();
      } catch {
        continue;
      }
      for (const f of files) {
        const path = join(dir, sub, f);
        let raw: string;
        try {
          raw = readFileSync(path, 'utf8');
        } catch {
          ds.push(warn('W_READ', `could not read ${path}`, { file: path, line: 1 }, 'Check that the file still exists and is readable'));
          continue;
        }
        const marker = readMarker(raw);
        if (!marker) continue;
        const p = resolve(marker.persona);
        if (!p) {
          ds.push(warn('W_STALE_RENDER', `${path} was rendered from ${marker.persona}, which no longer resolves`, { file: path, line: 1 }, 'Fix the persona, or delete the generated file'));
        } else if (p.sourceId !== marker.source) {
          // No --scope suggestion here: re-rendering with any scope resolves the *current*
          // (shadowing) source, never the one this file was generated from, so the only real
          // fix is to delete this file.
          ds.push(warn(
            'W_STALE_RENDER',
            `${path} was rendered from ${marker.source}, but ${marker.persona} now resolves to ${p.sourceId}`,
            { file: path, line: 1 },
            `Delete ${path}; ${marker.persona} now resolves to ${p.sourceId}`,
          ));
        } else if (inputHash(p) !== marker.hash) {
          ds.push(warn('W_STALE_RENDER', `${path} is out of date with ${marker.persona}`, { file: path, line: 1 }, runHint(marker.persona)));
        }
      }
    }
  }
  return ds;
}
