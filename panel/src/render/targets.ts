import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import type { EffectivePersona } from '../model/effective';
import { normalizeSource } from '../parse/frontmatter';
import { renderPrompt } from './prompt';

const RESOLVER_VERSION = '0.2.0';
export const MARKER = '# Generated by aska.';
// Files rendered before the rename to aska carry the old marker. They're still aska's to
// overwrite and to check for staleness.
const MARKERS = [MARKER, '# Generated by claude-personas.'];

function generatedStem(p: EffectivePersona): string {
  return p.canonical.replace(':', '--');
}

export function generatedName(p: EffectivePersona): string {
  return `${generatedStem(p)}-persona`;
}

export function generatedFileName(p: EffectivePersona): string {
  return `${generatedStem(p)}.persona.md`;
}

export function panelTools(p: EffectivePersona): string[] {
  const tools = ['Read', 'Grep', 'Glob'];
  const add = (t: string) => {
    if (!tools.includes(t)) tools.push(t);
  };
  for (const c of p.capabilities) add(c.kind === 'mcp' ? `mcp__${c.name}` : 'Skill');
  for (const t of p.tools) add(t);
  return tools;
}

export function inputHash(p: EffectivePersona, read: (path: string) => string = (f) => readFileSync(f, 'utf8')): string {
  const h = createHash('sha256');
  // Kept as 'claude-personas' on purpose: it seeds every rendered file's hash, so renaming it
  // would report every file rendered so far as out of date.
  h.update(`claude-personas ${RESOLVER_VERSION}\0`);
  const pairs = p.inputs.map((path, i) => [p.inputIds[i]!, path] as const).sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  for (const [id, path] of pairs) h.update(`${id}\0${read(path)}\0`);
  return `sha256:${h.digest('hex')}`;
}

function frontmatter(p: EffectivePersona, hash: string, fields: [string, string][]): string {
  return [
    '---',
    `${MARKER} Do not edit; edit the source persona and run \`persona render\`.`,
    `# source: ${p.sourceId}`,
    `# persona: ${p.canonical}`,
    `# hash: ${hash}`,
    ...fields.map(([k, v]) => `${k}: ${v}`),
    '---',
  ].join('\n');
}

export function outputStyleFile(p: EffectivePersona, hash: string): string {
  const head = frontmatter(p, hash, [
    ['name', JSON.stringify(generatedName(p))],
    ['description', JSON.stringify(p.description)],
    ['keep-coding-instructions', 'true'],
  ]);
  return `${head}\n\n${renderPrompt(p, 'swap')}`;
}

export function subagentFile(p: EffectivePersona, hash: string): string {
  const head = frontmatter(p, hash, [
    ['name', JSON.stringify(generatedName(p))],
    ['description', JSON.stringify(`Panel persona: ${p.description}`)],
    ['tools', JSON.stringify(panelTools(p).join(', '))],
  ]);
  return `${head}\n\n${renderPrompt(p, 'panel')}`;
}

export function readMarker(content: string): { source: string; persona: string; hash: string } | undefined {
  const lines = normalizeSource(content).split('\n');
  if (lines[0] !== '---' || !MARKERS.some((m) => lines[1]?.startsWith(m))) return undefined;
  const get = (key: string) => lines.slice(2, 6).find((l) => l.startsWith(`# ${key}: `))?.slice(key.length + 4);
  const source = get('source');
  const persona = get('persona');
  const hash = get('hash');
  return source && persona && hash ? { source, persona, hash } : undefined;
}
